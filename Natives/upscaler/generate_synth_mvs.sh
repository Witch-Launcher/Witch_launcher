#!/bin/sh
# Generate the SPIR-V header for synth_mvs.comp (embedded in ffx_bridge.cpp).
# Requires glslangValidator. Output: synth_mvs_vk.h in the same directory.
set -e
cd "$(dirname "$0")"

glslangValidator -V synth_mvs.comp -o synth_mvs.spv --target-env vulkan1.2 --quiet
python3 - synth_mvs.spv synth_mvs_vk.h <<'EOF'
import sys
src, dst = sys.argv[1], sys.argv[2]
data = open(src, 'rb').read()
lines = []
for i in range(0, len(data), 8):
    lines.append('    ' + ', '.join(f'0x{b:02x}' for b in data[i:i+8]) + ',')
with open(dst, 'w') as f:
    f.write('// GENERATED by generate_synth_mvs.sh from synth_mvs.comp - do not edit.\n')
    f.write('#pragma once\n')
    f.write('#include <cstdint>\n\n')
    f.write(f'static const uint32_t kSynthMvsSpirvSize = {len(data)};\n')
    f.write('static const uint8_t kSynthMvsSpirv[] = {\n')
    f.write('\n'.join(lines))
    f.write('\n};\n')
EOF
rm -f synth_mvs.spv
echo "generated synth_mvs_vk.h"
