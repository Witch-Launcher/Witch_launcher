#!/bin/sh
# Generate the SPIR-V header for fsr1_resolve.comp (embedded in ffx_bridge.cpp).
# Requires glslangValidator. Output: fsr1_resolve_vk.h in the same directory.
set -e
cd "$(dirname "$0")"

glslangValidator -V fsr1_resolve.comp -o fsr1_resolve.spv --target-env vulkan1.2 --quiet
python3 - fsr1_resolve.spv fsr1_resolve_vk.h <<'EOF'
import sys
src, dst = sys.argv[1], sys.argv[2]
data = open(src, 'rb').read()
lines = []
for i in range(0, len(data), 8):
    lines.append('    ' + ', '.join(f'0x{b:02x}' for b in data[i:i+8]) + ',')
with open(dst, 'w') as f:
    f.write('// GENERATED by generate_fsr1_resolve.sh from fsr1_resolve.comp - do not edit.\n')
    f.write('#pragma once\n')
    f.write('#include <cstdint>\n\n')
    f.write(f'static const uint32_t kFsr1ResolveSpirvSize = {len(data)};\n')
    f.write('static const uint8_t kFsr1ResolveSpirv[] = {\n')
    f.write('\n'.join(lines))
    f.write('\n};\n')
EOF
rm -f fsr1_resolve.spv
echo "generated fsr1_resolve_vk.h"
